#!/usr/bin/env bash
# Stage fleet OTLP Basic auth for opencode-swarm export (no secrets in JSON config).
# Reads kv/tenants/shared/otel-ingest-client via OpenBao (same contract as
# ~/.dotfiles/shell/bash/otel-env.sh public-ingest path).
set -euo pipefail

BAO_ADDR="${BAO_ADDR:-http://vault-active.vault.svc.cluster.local:8200}"
export BAO_ADDR
OUT="${HOME}/.config/centralcloud/otel-ingest.env"
PUBLIC_BASE="https://otel-ingest.centralcloud.net"
# The user unit's Nix wrapper used to replace PATH with coreutils only.
# Keep the login helper, bao, and kubectl visible before that happens.
export PATH="${HOME}/.local/bin:/run/current-system/sw/bin:${PATH:-}"

login="${HOME}/.local/bin/bao-login"
if [[ ! -x "$login" ]]; then
	echo "sync-opencode-swarm-otel-from-bao: bao-login missing at ${login}" >&2
	exit 1
fi
# Renews ~/.vault-token when it is missing or inside 10 minutes of expiry.
"$login"

if ! command -v bao >/dev/null 2>&1; then
	echo "sync-opencode-swarm-otel-from-bao: bao not in PATH" >&2
	exit 1
fi

user="$(
	bao kv get -field=username -mount=kv tenants/shared/otel-ingest-client 2>/dev/null
)" || true
pass="$(
	bao kv get -field=password -mount=kv tenants/shared/otel-ingest-client 2>/dev/null
)" || true
endpoint="$(
	bao kv get -field=endpoint -mount=kv tenants/shared/otel-ingest-client 2>/dev/null
)" || true

if [ -z "$user" ] || [ -z "$pass" ]; then
	echo "sync-opencode-swarm-otel-from-bao: OpenBao read failed (login/token or policy). Paths: kv/tenants/shared/otel-ingest-client" >&2
	exit 1
fi

endpoint="${endpoint:-$PUBLIC_BASE}"
endpoint="${endpoint%/}"
base64_bin="$(command -v base64)"
auth_header="Authorization=Basic $(printf '%s:%s' "$user" "$pass" | "$base64_bin" -w0 2>/dev/null || printf '%s:%s' "$user" "$pass" | "$base64_bin")"

mkdir -p "$(dirname "$OUT")"
umask 077
cat >"$OUT" <<EOF
# Generated by sync-opencode-swarm-otel-from-bao.sh — do not commit.
OTEL_EXPORTER_OTLP_TRACES_ENDPOINT=${endpoint}/v1/traces
OTEL_EXPORTER_OTLP_PROTOCOL=http/protobuf
OTEL_INGEST_USER=${user}
OTEL_INGEST_PASSWORD=${pass}
OTEL_EXPORTER_OTLP_HEADERS=${auth_header}
OTEL_SERVICE_NAME=opencode-swarm
DEPLOYMENT_ENVIRONMENT=dev
EOF
chmod 600 "$OUT"
echo "Wrote ${OUT} (chmod 600). Restart opencode serve with ~/.config/opencode/serve-with-otel.sh"
